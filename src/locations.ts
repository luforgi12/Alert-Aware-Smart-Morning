/** Райони вибраної області, відсортовані за назвою. */
export function districtsOf(oblastUid: number): District[] {
  return DISTRICTS.filter((d) => d.oblastUid === oblastUid).sort((a, b) =>
    a.name.localeCompare(b.name, 'uk')
  );
}

export function oblastByUid(uid: number | null): Oblast | undefined {
  return OBLASTS.find((o) => o.uid === uid);
}

export function districtByUid(uid: number | null): District | undefined {
  return DISTRICTS.find((d) => d.uid === uid);
}
